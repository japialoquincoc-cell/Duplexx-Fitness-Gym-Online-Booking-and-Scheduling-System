    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
 String em = email.getText().trim();
    String uN = username.getText().trim();
    String pW = new String(password.getPassword());

    if (em.isEmpty() || uN.isEmpty() || pW.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
    if (!em.matches("^[\\w.+-]+@[\\w-]+\\.[\\w.]+$")) {
        JOptionPane.showMessageDialog(this, "Enter a valid email address", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
    if (pW.length() < 6) {
        JOptionPane.showMessageDialog(this, "Password must be at least 6 characters", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    String url = "jdbc:mysql://localhost:3306/gym";
    String checkSql = "SELECT 1 FROM user WHERE username = ? OR email = ?";
    String insertSql = "INSERT INTO user (username, password, email) VALUES (?, ?, ?)";

    try (Connection con = DriverManager.getConnection(url, "root", "")) {

        try (PreparedStatement chk = con.prepareStatement(checkSql)) {
            chk.setString(1, uN);
            chk.setString(2, em);
            try (ResultSet rs = chk.executeQuery()) {
                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "Username or email already exists", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
        }

        try (PreparedStatement ps = con.prepareStatement(insertSql)) {
            ps.setString(1, uN);
            ps.setString(2, pW);   // use pW here if your Login doesn't hash yet
            ps.setString(3, em);
            ps.executeUpdate();
        }

        JOptionPane.showMessageDialog(this, "Account created successfully!");
        Login login = new Login();
        login.setLocationRelativeTo(null);
        login.setVisible(true);
        this.dispose();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }     // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

